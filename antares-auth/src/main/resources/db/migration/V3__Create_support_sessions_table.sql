-- Audited admin support sessions: a platform admin temporarily acts as a real user.
CREATE TABLE support_sessions
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id       BIGINT                   NOT NULL,
    target_user_id BIGINT                   NOT NULL,
    reason         VARCHAR(255)             NOT NULL,
    started_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    -- No foreign keys on purpose: the audit trail outlives deleted accounts
    ended_at       TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_support_sessions_admin_id ON support_sessions (admin_id);
