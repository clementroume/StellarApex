-- V1__Baseline.sql
-- Condensed baseline of the Antares schema (former V1-V9). One-off exception to "never edit an applied
-- migration" (roadmap D67): there is no real database yet, so the history was folded into one script
-- before the local wipe. It is meant to be condensed once more at the end of the roadmap, before the
-- first production release; after that, migrations are never edited again.
-- Column order follows the order in which the former migrations added the columns.

-- Users: accounts of every service. Roles and preferences; the athlete profile (division, birth year,
-- height) is optional, only the division and the age group derived from the birth year are shared.
CREATE TABLE users
(
    id                      BIGSERIAL PRIMARY KEY,
    first_name              VARCHAR(255),
    last_name               VARCHAR(255),
    email                   VARCHAR(255)                NOT NULL UNIQUE,
    password                VARCHAR(255)                NOT NULL,
    platform_role           VARCHAR(50)                 NOT NULL,
    enabled                 BOOLEAN                     NOT NULL DEFAULT TRUE,
    locale                  VARCHAR(10)                 NOT NULL DEFAULT 'en',
    theme                   VARCHAR(20)                 NOT NULL DEFAULT 'light',
    created_at              TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Display unit for loads: METRIC (kg) or IMPERIAL (lb). NULL = follow the language (fr: kg).
    unit_system             VARCHAR(10),
    -- Consent to show the user's name on public leaderboards (members of the user's gyms always see it)
    public_leaderboard_name BOOLEAN                     NOT NULL DEFAULT FALSE,
    -- UI colour palette, combined with the light/dark theme
    palette                 VARCHAR(20)                 NOT NULL DEFAULT 'ocean',
    -- New accounts start unverified and confirm their address by a mailed link
    email_verified          BOOLEAN                     NOT NULL DEFAULT FALSE,
    -- Last password change (reset or change): access tokens issued before it are refused
    password_changed_at     TIMESTAMP WITH TIME ZONE,
    -- Athlete profile (all optional): competition division, birth year (age divisions), height
    division                VARCHAR(10),
    birth_year              INTEGER,
    height_cm               INTEGER,
    CONSTRAINT chk_theme CHECK (theme IN ('light', 'dark')),
    CONSTRAINT chk_locale CHECK (locale ~ '^[a-z]{2}(-[A-Z]{2})?$'),
    CONSTRAINT chk_platform_role CHECK (platform_role IN ('ADMIN', 'USER')),
    CONSTRAINT chk_palette CHECK (palette IN ('ocean', 'chalk', 'volt', 'rig')),
    CONSTRAINT chk_users_division CHECK (division IN ('MEN', 'WOMEN')),
    CONSTRAINT chk_users_birth_year CHECK (birth_year BETWEEN 1900 AND 2100),
    CONSTRAINT chk_users_height CHECK (height_cm BETWEEN 100 AND 250)
);

-- Gyms: physical (box) or virtual (programming)
CREATE TABLE gyms
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(255) NOT NULL UNIQUE,
    description          TEXT,
    enrollment_code      VARCHAR(50),
    is_programming       BOOLEAN      NOT NULL DEFAULT FALSE,
    is_auto_subscription BOOLEAN      NOT NULL DEFAULT FALSE,
    status               VARCHAR(50)  NOT NULL DEFAULT 'PENDING_APPROVAL',
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE memberships
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    gym_id     BIGINT      NOT NULL,
    gym_role   VARCHAR(50) NOT NULL,
    status     VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_memberships_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_memberships_gym FOREIGN KEY (gym_id) REFERENCES gyms (id) ON DELETE CASCADE,
    CONSTRAINT uq_memberships_user_gym UNIQUE (user_id, gym_id),
    CONSTRAINT chk_gym_role CHECK (gym_role IN ('OWNER', 'PROGRAMMER', 'COACH', 'ATHLETE'))
);

-- Permissions granted to a membership (ElementCollection)
CREATE TABLE membership_permissions
(
    membership_id BIGINT      NOT NULL,
    permission    VARCHAR(50) NOT NULL,

    CONSTRAINT fk_membership_permissions_membership FOREIGN KEY (membership_id) REFERENCES memberships (id) ON DELETE CASCADE,
    -- Composite primary key: uniqueness (Set semantic) and index speed
    PRIMARY KEY (membership_id, permission)
);

CREATE INDEX idx_memberships_user_id ON memberships (user_id);
CREATE INDEX idx_memberships_gym_id ON memberships (gym_id);
CREATE INDEX idx_gyms_name ON gyms (name);

-- A gym has exactly one holder: OWNER (physical gym) or PROGRAMMER (virtual gym).
CREATE UNIQUE INDEX uq_memberships_gym_holder ON memberships (gym_id)
    WHERE gym_role IN ('OWNER', 'PROGRAMMER');

-- Audited admin support sessions: a platform admin temporarily acts as a real user.
CREATE TABLE support_sessions
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id       BIGINT                   NOT NULL,
    target_user_id BIGINT                   NOT NULL,
    reason         VARCHAR(255)             NOT NULL,
    started_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    -- No foreign keys on purpose: the audit trail outlives deleted accounts
    ended_at       TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_support_sessions_admin_id ON support_sessions (admin_id);

-- Body weight history: one measure per user and day, in kilograms (private to its owner)
CREATE TABLE body_weights
(
    id          BIGSERIAL PRIMARY KEY,
    user_id     BIGINT                      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    measured_on DATE                        NOT NULL,
    weight_kg   NUMERIC(5, 2)               NOT NULL CHECK (weight_kg BETWEEN 20 AND 400),
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_body_weights_user_day UNIQUE (user_id, measured_on)
);
